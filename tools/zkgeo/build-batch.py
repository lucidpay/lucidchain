#!/usr/bin/env python3
"""build-batch.py: build the batch.json input for `cmd/zkgeo prove`.

Output format (what the prover reads):
  {"window_start":..,"window_end":..,"area_salt":"0x..","area_cells":[..],
   "records":[{"x":..,"y":..,"t":..,"salt":"0x.."}]}

Records come from one of:
  --records FILE   JSON list of {"lon","lat","t"[,"salt"]} or {"x","y","t"[,"salt"]}
  --demo N         N synthetic records around Dubai (mirrors the test fixture)

The area (the set of allowed grid cells) comes from one of:
  --area-box LON_MIN LAT_MIN LON_MAX LAT_MAX   every cell inside the box
  --area-from-records                          the cells the records fall in
                                               (dev only: proves nothing real)

IMPORTANT: the proof is about the records tree the SIDECHAIN committed in the
checkpoint. The records, their order and their salts here must be exactly the
ones the sidechain used, or the on-chain records-root check rejects the proof.
Salts generated by this script are only correct if you also feed them to the
sidechain (use --demo or a fresh chain for dev).
"""
import argparse
import json
import os
import secrets
import sys
import time

# BN254 scalar field modulus: every salt must be below it.
FR_MODULUS = 0x30644E72E131A029B85045B68181585D2833E84879B9709143E1F593F0000001
COORD_BITS = 32        # must match circuit.go CoordBits
TIME_BITS = 40         # must match circuit.go TimeBits
MAX_U32 = 0xFFFFFFFF


def fail(msg):
    sys.exit(f"build-batch: {msg}")


def encode_lonlat(lon, lat):
    """Mirror of offchain.go EncodeLonLat (clamp, then truncate to uint32)."""
    def enc(v, span):
        f = v / span * 4294967296.0
        return int(min(max(f, 0.0), float(MAX_U32)))
    return enc(lon + 180.0, 360.0), enc(lat + 90.0, 180.0)


def cell_id(x, y, shift):
    """Mirror of offchain.go CellID."""
    w = COORD_BITS - shift
    return ((x >> shift) << w) | (y >> shift)


def parse_fr(value, what):
    """Parse a hex or decimal field element, require canonical (< modulus)."""
    try:
        n = int(value, 16) if isinstance(value, str) and value.lower().startswith("0x") else int(value)
    except (TypeError, ValueError):
        fail(f"{what}: not a number: {value!r}")
    if not 0 <= n < FR_MODULUS:
        fail(f"{what}: not below the BN254 field modulus")
    return n


def fmt_fr(n):
    # Always 32 bytes: the prover's decoder rejects shorter encodings.
    return "0x" + format(n, "064x")


def random_fr():
    return secrets.randbelow(FR_MODULUS)


def load_records(path, shift):
    try:
        with open(path) as f:
            raw = json.load(f)
    except (OSError, json.JSONDecodeError) as e:
        fail(f"cannot read {path}: {e}")
    if not isinstance(raw, list) or not raw:
        fail(f"{path}: expected a non-empty JSON list")
    recs = []
    for i, r in enumerate(raw):
        if "x" in r and "y" in r:
            x, y = int(r["x"]), int(r["y"])
        elif "lon" in r and "lat" in r:
            x, y = encode_lonlat(float(r["lon"]), float(r["lat"]))
        else:
            fail(f"record {i}: needs x,y or lon,lat")
        if "t" not in r:
            fail(f"record {i}: missing t (unix seconds)")
        salt = parse_fr(r["salt"], f"record {i} salt") if "salt" in r else random_fr()
        recs.append({"x": x, "y": y, "t": int(r["t"]), "salt": salt})
    return recs


def demo_records(n, shift, start):
    ax, ay = encode_lonlat(55.27, 25.20)
    step = 1 << shift
    pts = [(ax, ay), (ax + step, ay), (ax, ay + step), (ax + step, ay + step)]
    return [
        {"x": pts[i % 4][0], "y": pts[i % 4][1], "t": start + 10 * (i + 1), "salt": random_fr()}
        for i in range(n)
    ]


def box_cells(box, shift, max_cells):
    lon_min, lat_min, lon_max, lat_max = box
    if lon_min > lon_max or lat_min > lat_max:
        fail("--area-box: min must not exceed max")
    x0, y0 = encode_lonlat(lon_min, lat_min)
    x1, y1 = encode_lonlat(lon_max, lat_max)
    nx = (x1 >> shift) - (x0 >> shift) + 1
    ny = (y1 >> shift) - (y0 >> shift) + 1
    if nx * ny > max_cells:
        fail(f"--area-box covers {nx * ny} cells but the area tree holds {max_cells}; "
             f"shrink the box, raise --cell-shift, or raise --area-depth (needs a new key)")
    return [cell_id(cx << shift, cy << shift, shift)
            for cx in range(x0 >> shift, (x1 >> shift) + 1)
            for cy in range(y0 >> shift, (y1 >> shift) + 1)]


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    src = p.add_mutually_exclusive_group(required=True)
    src.add_argument("--records", metavar="FILE")
    src.add_argument("--demo", type=int, metavar="N")
    area = p.add_mutually_exclusive_group(required=True)
    area.add_argument("--area-box", type=float, nargs=4,
                      metavar=("LON_MIN", "LAT_MIN", "LON_MAX", "LAT_MAX"))
    area.add_argument("--area-from-records", action="store_true")
    p.add_argument("--area-salt", help="hex field element (default: random)")
    p.add_argument("--window-start", type=int)
    p.add_argument("--window-end", type=int)
    # Must equal the circuit parameters used at setup / prove time.
    p.add_argument("--cell-shift", type=int, default=14)
    p.add_argument("--capacity", type=int, default=8)
    p.add_argument("--area-depth", type=int, default=4)
    # Output location: folder and file name are separate parameters.
    p.add_argument("--out-dir", default=os.environ.get("BATCH_DIR", "."),
                   help="folder for the batch file, created if missing (env BATCH_DIR, default .)")
    p.add_argument("--out-name", default="batch.json", help="file name inside --out-dir")
    p.add_argument("--out", help="full path; overrides --out-dir and --out-name")
    p.add_argument("--force", action="store_true", help="overwrite --out")
    a = p.parse_args()

    if not 0 <= a.cell_shift < COORD_BITS:
        fail("--cell-shift out of range")
    if a.capacity < 1 or a.capacity & (a.capacity - 1):
        fail("--capacity must be a power of two")
    if not 1 <= a.area_depth <= 32:
        fail("--area-depth out of range")

    if a.demo is not None:
        if a.demo < 0:
            fail("--demo must be >= 0")
        start = a.window_start if a.window_start is not None else int(time.time())
        records = demo_records(a.demo, a.cell_shift, start)
    else:
        records = load_records(a.records, a.cell_shift)

    if len(records) > a.capacity:
        fail(f"{len(records)} records exceed capacity {a.capacity}")

    for i, r in enumerate(records):
        if not (0 <= r["x"] <= MAX_U32 and 0 <= r["y"] <= MAX_U32):
            fail(f"record {i}: x,y must fit in {COORD_BITS} bits")
        if not 0 <= r["t"] < (1 << TIME_BITS):
            fail(f"record {i}: t must fit in {TIME_BITS} bits")

    # Window: default is 10 s before the first record, 2 h long.
    if records:
        ts = [r["t"] for r in records]
        w_start = a.window_start if a.window_start is not None else min(ts) - 10
        w_end = a.window_end if a.window_end is not None else w_start + 7200
        if min(ts) < w_start or max(ts) > w_end:
            fail("a record timestamp lies outside [window_start, window_end]")
    else:
        w_start = a.window_start if a.window_start is not None else int(time.time())
        w_end = a.window_end if a.window_end is not None else w_start + 7200
    if not (0 <= w_start <= w_end < (1 << TIME_BITS)):
        fail("window must satisfy 0 <= start <= end < 2^40")

    max_cells = 1 << a.area_depth
    if a.area_box:
        cells = box_cells(a.area_box, a.cell_shift, max_cells)
    else:
        cells = sorted({cell_id(r["x"], r["y"], a.cell_shift) for r in records})
        if len(cells) > max_cells:
            fail(f"records span {len(cells)} cells but the area tree holds {max_cells}")
    if not cells:
        fail("the area is empty")

    cell_set = set(cells)
    outside = [i for i, r in enumerate(records)
               if cell_id(r["x"], r["y"], a.cell_shift) not in cell_set]
    if outside:
        fail(f"records {outside} fall outside the area (the prover would reject them)")

    area_salt = parse_fr(a.area_salt, "--area-salt") if a.area_salt else random_fr()

    batch = {
        "area_cells": cells,
        "area_salt": fmt_fr(area_salt),
        "records": [{"x": r["x"], "y": r["y"], "t": r["t"], "salt": fmt_fr(r["salt"])} for r in records],
        "window_end": w_end,
        "window_start": w_start,
    }

    out_path = a.out if a.out else os.path.join(a.out_dir, a.out_name)
    out_path = os.path.abspath(os.path.expanduser(out_path))
    try:
        os.makedirs(os.path.dirname(out_path), exist_ok=True)
    except OSError as e:
        fail(f"cannot create output folder: {e}")
    try:
        with open(out_path, "w" if a.force else "x") as f:
            json.dump(batch, f, indent=2)
            f.write("\n")
    except FileExistsError:
        fail(f"{out_path} exists; use --force to overwrite")

    print(f"wrote {out_path}: {len(records)} records, {len(cells)} area cells, "
          f"window [{w_start}, {w_end}]", file=sys.stderr)
    print("reminder: records, order and salts must match the sidechain's checkpoint tree",
          file=sys.stderr)


if __name__ == "__main__":
    main()